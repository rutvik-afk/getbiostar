/* ============================================================
   STEP 11 — Search Console export -> data/gsc-pages.json

   Usage:  node scripts/11-import-gsc.mjs <folder with Pages.csv and Chart.csv>
   (unzip the "Performance on Search" export, "Last 28 days" or longer)

   The build reads this file to decide which live pages Google has not shown
   yet, and links to them from pages it has (see unseenFor in
   src/lib/content.mjs). A page with no impression after ~10 days is the one
   that needs an inbound link from somewhere Google already visits.

   Refresh it from a new export every week or two; nothing else to do.
   ============================================================ */
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir || !fs.existsSync(path.join(dir, 'Pages.csv'))) {
  console.error('usage: node scripts/11-import-gsc.mjs <folder containing Pages.csv and Chart.csv>');
  process.exit(1);
}

function parseCSV(t) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (q) { if (c === '"') { if (t[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n') { row.push(f); rows.push(row); row = []; f = ''; }
    else if (c !== '\r') f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  return rows.slice(1).filter((r) => r.length > 1);
}

const ROOT = path.resolve(import.meta.dirname, '..');
const pages = parseCSV(fs.readFileSync(path.join(dir, 'Pages.csv'), 'utf8')).map((r) => ({
  slug: r[0].replace(/^https?:\/\/[^/]+\//, '').replace(/\/$/, ''),
  clicks: +r[1], impressions: +r[2], position: +r[4],
})).filter((p) => p.slug && /^[a-z0-9-]+$/.test(p.slug));

const chart = fs.existsSync(path.join(dir, 'Chart.csv'))
  ? parseCSV(fs.readFileSync(path.join(dir, 'Chart.csv'), 'utf8')).map((r) => r[0]).sort() : [];
if (!chart.length) { console.error('Chart.csv missing or empty — cannot tell what dates this covers'); process.exit(1); }

const out = {
  _note: 'Generated by scripts/11-import-gsc.mjs from a Search Console Performance export. Read at build time to find live pages Google has not shown yet. Regenerate from a fresh export; do not edit by hand.',
  windowStart: chart[0],
  /* The last day in a fresh export is partial, so it is only used to date the
     window; the 10-day grace period in unseenFor absorbs the difference. */
  windowEnd: chart[chart.length - 1],
  pages,
};
fs.writeFileSync(path.join(ROOT, 'data/gsc-pages.json'), JSON.stringify(out) + '\n');
console.log(`wrote data/gsc-pages.json: ${pages.length} pages with impressions, window ${out.windowStart} -> ${out.windowEnd}`);
